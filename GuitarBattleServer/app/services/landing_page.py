"""Server-rendered public landing page, robots.txt and sitemap.xml.

The landing page is a single HTML template (``app/static/landing/index.html``)
with ``{{ key }}`` placeholders. The API renders it twice, once per language,
so a crawler that never runs JavaScript still receives the real title,
description, Open Graph tags and body copy:

    GET /      -> <html lang="ru"> ... Russian document
    GET /en    -> <html lang="en"> ... English document

Both variants keep the ``data-i18n`` hooks, so the client-side language
switcher (``app/static/app/i18n.js``) keeps working and re-paints the page in
place. The text itself lives in :mod:`app.services.landing_content`.

``robots.txt`` and ``sitemap.xml`` are generated here as well: the sitemap lists
the two language variants with ``xhtml:link`` alternates and the public static
pages, and takes ``lastmod`` from the template mtime so it follows the content
without a manual bump.
"""
from __future__ import annotations

import json
import re
from datetime import date, datetime, timezone
from functools import lru_cache
from html import escape
from pathlib import Path
from typing import Final
from xml.sax.saxutils import escape as xml_escape

from app.services.landing_content import (
    DEFAULT_LANGUAGE,
    IN_LANGUAGE,
    LANDING_TEXT,
    LANGUAGES,
    OG_LOCALE,
    OG_LOCALE_ALTERNATE,
)

# Canonical origin of the public site. The reverse proxy publishes only
# https://fretfight.online, so absolute URLs in metadata are pinned to it and
# never depend on the incoming Host header.
SITE_ORIGIN: Final = "https://fretfight.online"

STATIC_DIR = Path(__file__).resolve().parents[1] / "static"
LANDING_TEMPLATE = STATIC_DIR / "landing" / "index.html"

# Public path of each language variant. ``/`` is the Russian document and the
# x-default; ``/en`` is the English one. Each variant is canonical for itself.
LANGUAGE_PATHS: Final[dict[str, str]] = {"ru": "/", "en": "/en"}

# Social preview cards, 1200x630 PNG, generated by scripts/build_og_image.ps1.
OG_IMAGE_PATHS: Final[dict[str, str]] = {
    "ru": "/app/og-image.png",
    "en": "/app/og-image-en.png",
}
OG_IMAGE_WIDTH: Final = 1200
OG_IMAGE_HEIGHT: Final = 630
LOGO_PATH: Final = "/app/logo.png"
LOGO_SIZE: Final = 600

# Private or non-HTML sections. Everything else stays crawlable, including the
# pages listed in the sitemap.
ROBOTS_DISALLOW: Final = ("/account", "/admin/", "/api/")

# (path, priority, has language alternates)
SITEMAP_PAGES: Final[tuple[tuple[str, str, bool], ...]] = (
    ("/", "1.0", True),
    ("/en", "0.9", True),
    ("/support", "0.5", False),
    ("/register", "0.4", False),
    ("/policy", "0.3", False),
    ("/login", "0.3", False),
)

_PLACEHOLDER = re.compile(r"\{\{(?P<raw>!?)\s*(?P<key>[A-Za-z0-9_.]+)\s*\}\}")


def absolute_url(path: str) -> str:
    """Absolute URL on the public site for a root-relative path."""
    return f"{SITE_ORIGIN}{path}"


@lru_cache(maxsize=2)
def _template(mtime: float) -> str:
    """Read the template once per modification (mtime is the cache key)."""
    del mtime  # only used to invalidate the cache
    return LANDING_TEMPLATE.read_text(encoding="utf-8")


def _html_attributes(lang: str) -> str:
    """Attributes of the ``<html>`` element.

    ``data-lang-paths`` lets the switcher keep the URL in sync with the shown
    language, and ``data-lang-default`` pins a variant: a visitor who opens
    ``/en`` gets English even if the language cookie says otherwise.
    """
    paths = json.dumps(LANGUAGE_PATHS, ensure_ascii=False, separators=(",", ":"))
    attributes = [f'lang="{lang}"', f"data-lang-paths='{paths}'"]
    if lang != DEFAULT_LANGUAGE:
        attributes.append(f'data-lang-default="{lang}"')
    return " ".join(attributes)


def _structured_data(lang: str) -> dict:
    """JSON-LD graph for one language variant.

    Everything here is visible on the page: the app description, the free
    offer, the FAQ answers. No ratings or reviews are invented.
    """
    text = LANDING_TEXT[lang]
    root = f"{SITE_ORIGIN}/"
    return {
        "@context": "https://schema.org",
        "@graph": [
            {
                "@type": "SoftwareApplication",
                "name": "fretfight",
                "alternateName": "GuitarBattle",
                "applicationCategory": "GameApplication",
                "operatingSystem": "Windows 10, Windows 11",
                "url": root,
                "image": absolute_url(OG_IMAGE_PATHS[lang]),
                "description": text["landing.meta"],
                "inLanguage": IN_LANGUAGE[lang],
                "isAccessibleForFree": True,
                "offers": [
                    {"@type": "Offer", "price": "0", "priceCurrency": "RUB"},
                    {"@type": "Offer", "price": "0", "priceCurrency": "USD"},
                ],
            },
            {
                "@type": "Organization",
                "name": "fretfight",
                "url": root,
                "logo": {
                    "@type": "ImageObject",
                    "url": absolute_url(LOGO_PATH),
                    "width": LOGO_SIZE,
                    "height": LOGO_SIZE,
                },
            },
            # No potentialAction: the site has no search box, and advertising a
            # SearchAction that does not exist is worse than omitting it.
            {
                "@type": "WebSite",
                "name": "fretfight",
                "url": root,
                "inLanguage": [IN_LANGUAGE["ru"], IN_LANGUAGE["en"]],
            },
            {
                "@type": "FAQPage",
                "inLanguage": IN_LANGUAGE[lang],
                "mainEntity": [
                    {
                        "@type": "Question",
                        "name": text[f"landing.faq.q{index}"],
                        "acceptedAnswer": {
                            "@type": "Answer",
                            "text": text[f"landing.faq.a{index}"],
                        },
                    }
                    for index in (1, 2, 3, 4)
                ],
            },
        ],
    }


def _json_ld(lang: str) -> str:
    # Compact separators keep the inline script small; ensure_ascii=False keeps
    # the Cyrillic readable. The payload is built from our own constants only.
    return json.dumps(_structured_data(lang), ensure_ascii=False, separators=(",", ":"))


def _values(lang: str) -> dict[str, str]:
    """Placeholder values for one language variant."""
    values = dict(LANDING_TEXT[lang])
    values.update(
        {
            "html_attrs": _html_attributes(lang),
            "canonical": absolute_url(LANGUAGE_PATHS[lang]),
            "site_origin": SITE_ORIGIN,
            "og_locale": OG_LOCALE[lang],
            "og_locale_alternate": OG_LOCALE_ALTERNATE[lang],
            "og_image": absolute_url(OG_IMAGE_PATHS[lang]),
            "json_ld": _json_ld(lang),
        }
    )
    return values


def render_landing(lang: str) -> str:
    """Render the landing page for ``lang`` (``ru`` or ``en``).

    The output is cached per (language, template mtime): this is the most
    requested URL on the site and it only changes when the template changes.
    """
    if lang not in LANGUAGES:
        raise ValueError(f"Unsupported landing language: {lang!r}")
    return _render_cached(lang, LANDING_TEMPLATE.stat().st_mtime)


@lru_cache(maxsize=4)
def _render_cached(lang: str, mtime: float) -> str:
    template = _template(mtime)
    values = _values(lang)

    def replace(match: re.Match[str]) -> str:
        key = match.group("key")
        try:
            value = values[key]
        except KeyError:  # pragma: no cover - a typo in the template
            raise KeyError(f"Unknown landing placeholder: {key}") from None
        return value if match.group("raw") else escape(value)

    return _PLACEHOLDER.sub(replace, template)


def last_modified() -> str:
    """``lastmod`` for the sitemap: the date the landing content changed.

    The Docker build copies the static files, so the template mtime follows a
    release without a hard-coded date that would silently go stale.
    """
    try:
        stamp = LANDING_TEMPLATE.stat().st_mtime
    except OSError:  # pragma: no cover - the template always ships
        return date.today().isoformat()
    return datetime.fromtimestamp(stamp, tz=timezone.utc).date().isoformat()


def robots_txt() -> str:
    lines = ["User-agent: *", "Allow: /"]
    lines.extend(f"Disallow: {path}" for path in ROBOTS_DISALLOW)
    lines.extend(["", f"Sitemap: {absolute_url('/sitemap.xml')}", ""])
    return "\n".join(lines)


def sitemap_xml() -> str:
    origin = SITE_ORIGIN
    modified = last_modified()
    entries: list[str] = []
    for path, priority, has_alternates in SITEMAP_PAGES:
        lines = [
            "  <url>",
            f"    <loc>{xml_escape(origin + path)}</loc>",
            f"    <lastmod>{modified}</lastmod>",
            f"    <priority>{priority}</priority>",
        ]
        if has_alternates:
            for lang in LANGUAGES:
                lines.append(
                    '    <xhtml:link rel="alternate" hreflang="{}" href="{}"/>'.format(
                        lang, xml_escape(origin + LANGUAGE_PATHS[lang])
                    )
                )
            lines.append(
                '    <xhtml:link rel="alternate" hreflang="x-default" href="{}"/>'.format(
                    xml_escape(origin + LANGUAGE_PATHS["ru"])
                )
            )
        lines.append("  </url>")
        entries.append("\n".join(lines))
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"\n'
        '        xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
        + "\n".join(entries)
        + "\n</urlset>\n"
    )
