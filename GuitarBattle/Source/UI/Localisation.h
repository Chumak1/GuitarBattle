    inline Language language() noexcept
    {
        return detail::current().load (std::memory_order_relaxed);
    }

    inline void setLanguage (Language newLanguage)
    {
        if (detail::current().load (std::memory_order_relaxed) == newLanguage)
            return;

        detail::current().store (newLanguage, std::memory_order_relaxed);

        for (auto& listener : detail::listeners())
        {
            if (listener != nullptr)
                listener();
        }
    }

    // Called after the language changed so already-built widgets can refresh
    // their cached text and repaint. Captures should use SafePointer.
    inline void addLanguageListener (std::function<void()> listener)
    {
        detail::listeners().push_back (std::move (listener));
    }

    inline juce::String code (Language which)
    {
        return which == Language::russian ? "ru" : "en";
    }

    inline Language fromCode (const juce::String& value)
    {
        return value.trim().toLowerCase().startsWith ("ru")
                   ? Language::russian
                   : Language::english;
    }

    inline juce::String tr (const juce::String& english)
    {
        if (language() == Language::english)
            return english;

        const auto* entries = detail::table();

        for (int i = 0; i < detail::tableSize; ++i)
        {
            if (english == entries[i].en)
                return juce::String (juce::CharPointer_UTF8 (entries[i].ru));
        }

        return english;
    }

    inline juce::String name (Language which)
    {
        return which == Language::russian
                   ? tr (juce::String (juce::CharPointer_UTF8 ("\xD0\xA0\xD1\x83\xD1\x81\xD1\x81\xD0\xBA\xD0\xB8\xD0\xB9")))
                   : juce::String ("English");
    }

    inline bool isRussian() noexcept
    {
        return language() == Language::russian;
    }
